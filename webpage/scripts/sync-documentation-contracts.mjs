import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const inventoryPath = resolve(root, "doc/documentation-inventory.json");
const terminologyPath = resolve(root, "doc/terminology.json");
const outputPath = resolve(here, "../src/data/documentation-contracts.js");
const checkOnly = process.argv.includes("--check");

const requiredRecordFields = [
  "id", "owner", "symbol", "kind", "category", "source_evidence",
  "test_evidence", "call_forms_options", "inputs", "return_type_shape",
  "validation_errors", "supported_scope", "tex_anchor", "tex_index",
  "tex_example_evidence", "web_route_or_anchor", "web_example_evidence",
  "executable_example",
];

function fail(message) {
  throw new Error(`[documentation-contracts] ${message}`);
}

function unique(values, label) {
  if (new Set(values).size !== values.length) fail(`${label} values must be unique.`);
}

const inventory = JSON.parse(await readFile(inventoryPath, "utf8"));
const terminology = JSON.parse(await readFile(terminologyPath, "utf8"));

if (inventory.schema_version !== 2) fail("Expected documentation inventory schema_version 2.");
if (inventory.version !== "v1.3.2") fail("Expected documentation inventory version v1.3.2.");
if (!Array.isArray(inventory.records) || inventory.records.length !== 192) {
  fail(`Expected 192 public API records, found ${inventory.records?.length ?? "none"}.`);
}
unique(inventory.records.map((record) => record.id), "Inventory record id");
for (const record of inventory.records) {
  for (const field of requiredRecordFields) {
    if (!(field in record)) fail(`Record ${record.id} is missing ${field}.`);
  }
  if (record.executable_example !== true) fail(`Record ${record.id} lacks executable example evidence.`);
  if (!record.web_route_or_anchor.startsWith("/")) fail(`Record ${record.id} has a non-root Web route.`);
  if (!record.web_route_or_anchor.includes("#api-")) fail(`Record ${record.id} lacks a stable api-* anchor.`);
  if (!record.web_example_evidence.includes("#api-") || !record.web_example_evidence.endsWith("-example")) {
    fail(`Record ${record.id} lacks a stable example anchor.`);
  }
}

if (terminology.schema_version !== 1) fail("Expected terminology schema_version 1.");
if (!Array.isArray(terminology.terms) || terminology.terms.length !== 8) {
  fail(`Expected 8 governed terms, found ${terminology.terms?.length ?? "none"}.`);
}
unique(terminology.terms.map((term) => term.id), "Terminology id");
unique(terminology.terms.map((term) => term.abbreviation), "Terminology abbreviation");
for (const term of terminology.terms) {
  for (const field of ["id", "abbreviation", "expansion", "aliases", "tex_index_key", "web_definition_anchor", "auto_link"]) {
    if (!(field in term)) fail(`Term ${term.id} is missing ${field}.`);
  }
}

const ownerCounts = Object.fromEntries(
  ["pdbase", "pdmat", "pdvar", "pdlmi", "helper", "root"].map((owner) => [
    owner,
    inventory.records.filter((record) => record.owner === owner).length,
  ]),
);

const generated = `// Generated by scripts/sync-documentation-contracts.mjs.
// Sources: doc/documentation-inventory.json and doc/terminology.json.
// Do not edit by hand.

export const documentationVersion = ${JSON.stringify(inventory.version)};
export const documentationRecords = ${JSON.stringify(inventory.records, null, 2)};
export const documentationPresentationGroups = ${JSON.stringify(inventory.presentation_groups, null, 2)};
export const terminologyTerms = ${JSON.stringify(terminology.terms, null, 2)};
export const excludedGeneralAbbreviations = ${JSON.stringify(terminology.excluded_general_abbreviations, null, 2)};
export const documentationContractSummary = ${JSON.stringify({ records: inventory.records.length, terms: terminology.terms.length, ownerCounts }, null, 2)};
`;

if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) fail("Generated Web projection is stale. Run npm --prefix webpage run sync:contracts.");
  console.log(`Documentation contract projection is current (${inventory.records.length} records, ${terminology.terms.length} terms).`);
} else {
  await writeFile(outputPath, generated, "utf8");
  console.log(`Synchronized ${inventory.records.length} records and ${terminology.terms.length} terms to ${outputPath}.`);
}
